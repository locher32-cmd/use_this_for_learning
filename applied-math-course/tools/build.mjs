// Build step (no dependencies). Run: node tools/build.mjs
//  1. Regenerates sw.js so the offline cache lists every file the app needs, versioned by content hash.
//  2. Writes dist/artifact.html: the page as a fragment (no <html>/<head>/<body>) for hosts that wrap pages.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const walk = (dir) => fs.readdirSync(path.join(root, dir), { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]));
const assets = ['index.html', 'manifest.webmanifest', ...['css', 'js', 'vendor', 'icons'].flatMap(walk)]
  .map((p) => p.split(path.sep).join('/'))
  .filter((p) => !/LICENSE|\.txt$|\.md$/.test(p))
  .sort();

const hash = crypto.createHash('sha256');
assets.forEach((a) => hash.update(a).update(fs.readFileSync(path.join(root, a))));
const version = hash.digest('hex').slice(0, 12);

const sw = `/* Generated by tools/build.mjs: do not edit by hand. Offline cache for Gradient. */
const CACHE = 'gradient-${version}';
const ASSETS = ${JSON.stringify(assets, null, 1)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('gradient-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
      return res;
    }).catch(() => (req.mode === 'navigate' ? caches.match('index.html') : undefined)))
  );
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);

const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const fragment = html
  .replace(/<!doctype html>\s*/i, '')
  .replace(/<\/?(html|head|body)[^>]*>\s*/gi, '')
  .replace(/<meta charset[^>]*>\s*/i, '')
  .replace(/<meta name="viewport"[^>]*>\s*/i, '')
  .replace(/<meta http-equiv="Content-Security-Policy"[^>]*>\s*/i, ''); // the hosting page sets its own policy
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'artifact.html'), fragment);
console.log(`sw.js: ${assets.length} files, cache version ${version}`);
console.log('dist/artifact.html written');
